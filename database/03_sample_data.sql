-- 1. SAMPLE WAREHOUSE
MERGE INTO WAREHOUSES w
USING (
    SELECT
        'WH01' AS WAREHOUSE_CODE,
        'Kho nguyen lieu' AS WAREHOUSE_NAME
    FROM DUAL
) s
ON (w.WAREHOUSE_CODE = s.WAREHOUSE_CODE)

WHEN NOT MATCHED THEN
    INSERT (WAREHOUSE_CODE, WAREHOUSE_NAME)
    VALUES (s.WAREHOUSE_CODE, s.WAREHOUSE_NAME);


-- 2. SAMPLE MATERIALS
MERGE INTO MATERIALS m
USING (
    SELECT 'MAT001' AS MATERIAL_CODE,
           'Thep tam' AS MATERIAL_NAME,
           'KG' AS UNIT,
           100 AS REORDER_LEVEL,
           'ACTIVE' AS STATUS
    FROM DUAL

    UNION ALL

    SELECT 'MAT002', 'Oc vit', 'PCS', 200, 'ACTIVE'
    FROM DUAL

    UNION ALL

    SELECT 'MAT003', 'Vo nhua', 'PCS', 150, 'ACTIVE'
    FROM DUAL

    UNION ALL

    SELECT 'MAT004', 'Day dien', 'M', 50, 'ACTIVE'
    FROM DUAL
) s

ON (m.MATERIAL_CODE = s.MATERIAL_CODE)

WHEN NOT MATCHED THEN
    INSERT (
        MATERIAL_CODE,
        MATERIAL_NAME,
        UNIT,
        REORDER_LEVEL,
        STATUS
    )
    VALUES (
        s.MATERIAL_CODE,
        s.MATERIAL_NAME,
        s.UNIT,
        s.REORDER_LEVEL,
        s.STATUS
    );


-- 3. INITIAL STOCK BALANCES
MERGE INTO STOCK_BALANCES b
USING (
    SELECT m.MATERIAL_ID,
           w.WAREHOUSE_ID,
           70 AS QUANTITY
    FROM MATERIALS m
    CROSS JOIN WAREHOUSES w
    WHERE m.MATERIAL_CODE = 'MAT001'
      AND w.WAREHOUSE_CODE = 'WH01'

    UNION ALL

    SELECT m.MATERIAL_ID,
           w.WAREHOUSE_ID,
           350 AS QUANTITY
    FROM MATERIALS m
    CROSS JOIN WAREHOUSES w
    WHERE m.MATERIAL_CODE = 'MAT002'
      AND w.WAREHOUSE_CODE = 'WH01'

    UNION ALL

    SELECT m.MATERIAL_ID,
           w.WAREHOUSE_ID,
           100 AS QUANTITY
    FROM MATERIALS m
    CROSS JOIN WAREHOUSES w
    WHERE m.MATERIAL_CODE = 'MAT003'
      AND w.WAREHOUSE_CODE = 'WH01'

    UNION ALL

    SELECT m.MATERIAL_ID,
           w.WAREHOUSE_ID,
           80 AS QUANTITY
    FROM MATERIALS m
    CROSS JOIN WAREHOUSES w
    WHERE m.MATERIAL_CODE = 'MAT004'
      AND w.WAREHOUSE_CODE = 'WH01'
) s

ON (
    b.MATERIAL_ID = s.MATERIAL_ID
    AND b.WAREHOUSE_ID = s.WAREHOUSE_ID
)

WHEN NOT MATCHED THEN
    INSERT (
        MATERIAL_ID,
        WAREHOUSE_ID,
        QUANTITY
    )
    VALUES (
        s.MATERIAL_ID,
        s.WAREHOUSE_ID,
        s.QUANTITY
    );


-- 4. COMMIT SAMPLE DATA
COMMIT;


-- 5. VERIFY SAMPLE DATA
SELECT
    m.MATERIAL_CODE,
    m.MATERIAL_NAME,
    m.UNIT,
    w.WAREHOUSE_CODE,
    b.QUANTITY,
    m.REORDER_LEVEL
FROM STOCK_BALANCES b
JOIN MATERIALS m
    ON b.MATERIAL_ID = m.MATERIAL_ID
JOIN WAREHOUSES w
    ON b.WAREHOUSE_ID = w.WAREHOUSE_ID
ORDER BY m.MATERIAL_CODE;
