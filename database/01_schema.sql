-- 1. MATERIALS
-- Danh muc vat tu
CREATE TABLE MATERIALS (
    MATERIAL_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    MATERIAL_CODE VARCHAR2(30) NOT NULL,
    MATERIAL_NAME VARCHAR2(100) NOT NULL,
    UNIT VARCHAR2(20) NOT NULL,

    REORDER_LEVEL NUMBER(12,2)
        DEFAULT 0 NOT NULL,

    STATUS VARCHAR2(10)
        DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_MATERIALS
        PRIMARY KEY (MATERIAL_ID),

    CONSTRAINT UQ_MATERIALS_CODE
        UNIQUE (MATERIAL_CODE),

    CONSTRAINT CK_MATERIAL_REORDER
        CHECK (REORDER_LEVEL >= 0),

    CONSTRAINT CK_MATERIAL_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


-- 2. WAREHOUSES
-- Danh muc kho
CREATE TABLE WAREHOUSES (
    WAREHOUSE_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    WAREHOUSE_CODE VARCHAR2(30) NOT NULL,
    WAREHOUSE_NAME VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_WAREHOUSES
        PRIMARY KEY (WAREHOUSE_ID),

    CONSTRAINT UQ_WAREHOUSE_CODE
        UNIQUE (WAREHOUSE_CODE)
);


-- 3. STOCK_BALANCES
-- So luong ton kho hien tai
CREATE TABLE STOCK_BALANCES (
    MATERIAL_ID NUMBER NOT NULL,
    WAREHOUSE_ID NUMBER NOT NULL,

    QUANTITY NUMBER(12,2)
        DEFAULT 0 NOT NULL,

    CONSTRAINT PK_STOCK_BALANCES
        PRIMARY KEY (MATERIAL_ID, WAREHOUSE_ID),

    CONSTRAINT CK_BALANCE_QUANTITY
        CHECK (QUANTITY >= 0),

    CONSTRAINT FK_BALANCE_MATERIAL
        FOREIGN KEY (MATERIAL_ID)
        REFERENCES MATERIALS (MATERIAL_ID),

    CONSTRAINT FK_BALANCE_WAREHOUSE
        FOREIGN KEY (WAREHOUSE_ID)
        REFERENCES WAREHOUSES (WAREHOUSE_ID)
);


-- 4. STOCK_TRANSACTIONS
-- Lich su giao dich nhap xuat kho
CREATE TABLE STOCK_TRANSACTIONS (
    TRANSACTION_ID NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    MATERIAL_ID NUMBER NOT NULL,
    WAREHOUSE_ID NUMBER NOT NULL,

    TRANSACTION_TYPE VARCHAR2(3) NOT NULL,
    QUANTITY NUMBER(12,2) NOT NULL,

    TRANSACTION_DATE TIMESTAMP(6)
        DEFAULT SYSTIMESTAMP NOT NULL,

    REFERENCE_NO VARCHAR2(50),
    NOTE VARCHAR2(500),

    CREATED_BY VARCHAR2(30)
        DEFAULT USER NOT NULL,

    CONSTRAINT PK_STOCK_TRANSACTIONS
        PRIMARY KEY (TRANSACTION_ID),

    CONSTRAINT CK_STOCK_TYPE
        CHECK (TRANSACTION_TYPE IN ('IN', 'OUT')),

    CONSTRAINT CK_STOCK_QUANTITY
        CHECK (QUANTITY > 0),

    CONSTRAINT FK_STOCK_MATERIAL
        FOREIGN KEY (MATERIAL_ID)
        REFERENCES MATERIALS (MATERIAL_ID),

    CONSTRAINT FK_STOCK_WAREHOUSE
        FOREIGN KEY (WAREHOUSE_ID)
        REFERENCES WAREHOUSES (WAREHOUSE_ID)
);
